// Completes `vite build --mode server` (npm run build:server) for our server: the files go in
// the server folder /frontend/restainup/, which is the root of https://www.restainup.it
// (see .env.server). Consent records still go to VITE_CONSENT_API_URL (https://amosport.it).
//  - sitemap.xml and an indexable robots.txt for the domain;
//  - .htaccess for the SPA routing (the server is Apache);
//  - opens dist/, whose content is uploaded to /frontend/restainup/.
import { execSync } from 'child_process';
import { writeFileSync } from 'fs';
import { join } from 'path';
import { loadEnv } from 'vite';

const env = loadEnv('server', process.cwd(), '');
const basePath = (env.VITE_BASE_PATH || '/').replace(/\/?$/, '/');
const siteUrl = `${env.VITE_SITE_ORIGIN}${basePath.replace(/\/$/, '')}`;
const distDir = join(process.cwd(), 'dist');

execSync('node scripts/generate-sitemap.mjs', {
  stdio: 'inherit',
  env: { ...process.env, SITEMAP_SITE_URL: siteUrl, SITEMAP_OUT: 'dist/sitemap.xml' },
});

// public/robots.txt is the closed one of the GitHub Pages preview: replace it.
const indexable = !/noindex/i.test(env.VITE_ROBOTS || '');
writeFileSync(
  join(distDir, 'robots.txt'),
  indexable
    ? `User-agent: *\nAllow: /\n\nSitemap: ${siteUrl}/sitemap.xml\n`
    : 'User-agent: *\nDisallow: /\n',
);

writeFileSync(
  join(distDir, '.htaccess'),
  `# Apache configuration for ${siteUrl}/ (generated by scripts/build-server.mjs).
Options -MultiViews -Indexes
DirectoryIndex index.html
AddDefaultCharset UTF-8
AddType video/mp4 .mp4
AddType image/webp .webp

<IfModule mod_rewrite.c>
  RewriteEngine On
  RewriteBase ${basePath}

  # --- Enable once the domain and its SSL certificate are active on the server ---
  # Force https:
  # RewriteCond %{HTTPS} off
  # RewriteRule ^ https://%{HTTP_HOST}%{REQUEST_URI} [L,R=301]
  # Always use the www version:
  # RewriteCond %{HTTP_HOST} ^restainup\\.it$ [NC]
  # RewriteRule ^ https://www.restainup.it%{REQUEST_URI} [L,R=301]

  # Existing files and folders (JS, CSS, images...) are served as they are
  RewriteCond %{REQUEST_FILENAME} -f [OR]
  RewriteCond %{REQUEST_FILENAME} -d
  RewriteRule ^ - [L]

  # Every other address is a route of the app: served by index.html
  RewriteRule ^ ${basePath}index.html [L]
</IfModule>

<IfModule mod_deflate.c>
  AddOutputFilterByType DEFLATE text/html text/css text/plain text/xml application/javascript application/json application/xml image/svg+xml
</IfModule>

<IfModule mod_expires.c>
  ExpiresActive On
  # Built JS/CSS/images have a content hash in the name: safe to cache for a long time
  <If "%{REQUEST_URI} =~ m#^${basePath}assets/#">
    ExpiresDefault "access plus 1 year"
  </If>
  ExpiresByType text/html "access plus 0 seconds"
</IfModule>
`,
);
console.log(`robots.txt (${indexable ? 'indexable' : 'closed'}) and .htaccess written for ${siteUrl}/`);

// Open the output folder: its content goes in /frontend/restainup/ on the server.
console.log(`Build ready in dist/ -> upload its content to /frontend/restainup/ on the server (${siteUrl}/)`);
const opener = process.platform === 'win32' ? 'explorer' : process.platform === 'darwin' ? 'open' : 'xdg-open';
try {
  execSync(`${opener} "${distDir}"`, { stdio: 'ignore' });
} catch {
  // explorer.exe exits with code 1 even when it opens the folder.
}
